import * as Print from 'expo-print';
import { MedicationAdherence, getAdherenceReport, getOverallAdherence } from '../db/reports';
import { getUserProfile } from './userProfile';

/** Generate HTML string for the adherence report */
export function generateReportHTML(
  patientName: string,
  patientAge: number,
  startDate: string,
  endDate: string,
  medications: MedicationAdherence[],
  overallAdherence: number
): string {
  const generatedDate = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const adherenceColor =
    overallAdherence >= 80 ? '#2E7D32' : overallAdherence >= 50 ? '#F57F17' : '#C62828';

  const medicationRows =
    medications.length > 0
      ? medications
          .map(
            (med) => `
        <tr>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0;">${med.medicationName}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0;">${med.dosage ?? '—'}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0; text-align: center;">${med.taken}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0; text-align: center;">${med.skipped}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0; text-align: center;">${med.snoozed}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0; text-align: center;">${med.totalScheduled}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e0e0e0;">
            <div style="background: #e0e0e0; border-radius: 4px; height: 20px; width: 100%; position: relative;">
              <div style="background: ${med.adherencePercent >= 80 ? '#2E7D32' : med.adherencePercent >= 50 ? '#F57F17' : '#C62828'}; border-radius: 4px; height: 100%; width: ${med.adherencePercent}%;"></div>
            </div>
            <span style="font-size: 12px; color: #666;">${med.adherencePercent}%</span>
          </td>
        </tr>`
          )
          .join('')
      : `<tr><td colspan="7" style="padding: 20px; text-align: center; color: #999;">No medication data for this period.</td></tr>`;

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>MediBuddy Adherence Report</title>
</head>
<body style="font-family: 'Helvetica Neue', Arial, sans-serif; margin: 0; padding: 0; color: #333; background: #fff;">
  <!-- Header -->
  <div style="background: #0F3D3E; color: white; padding: 24px 32px; text-align: center;">
    <h1 style="margin: 0; font-size: 24px;">💊 MediBuddy</h1>
    <p style="margin: 4px 0 0; font-size: 14px; opacity: 0.85;">Medication Adherence Report</p>
  </div>

  <div style="padding: 24px 32px; max-width: 800px; margin: 0 auto;">
    <!-- Patient Info -->
    <div style="background: #f5f5f5; border-radius: 8px; padding: 16px 20px; margin-bottom: 24px;">
      <h2 style="margin: 0 0 8px; font-size: 16px; color: #0F3D3E;">Patient Information</h2>
      <p style="margin: 4px 0;"><strong>Name:</strong> ${patientName}</p>
      <p style="margin: 4px 0;"><strong>Age:</strong> ${patientAge}</p>
      <p style="margin: 4px 0;"><strong>Report Period:</strong> ${startDate} to ${endDate}</p>
    </div>

    <!-- Overall Score -->
    <div style="text-align: center; margin-bottom: 24px; padding: 20px; border: 2px solid ${adherenceColor}; border-radius: 12px;">
      <p style="margin: 0 0 4px; font-size: 14px; color: #666;">Overall Adherence</p>
      <p style="margin: 0; font-size: 48px; font-weight: bold; color: ${adherenceColor};">${overallAdherence}%</p>
    </div>

    <!-- Medication Table -->
    <h2 style="font-size: 18px; color: #0F3D3E; margin-bottom: 12px;">Medication Breakdown</h2>
    <table style="width: 100%; border-collapse: collapse; font-size: 14px;">
      <thead>
        <tr style="background: #0F3D3E; color: white;">
          <th style="padding: 10px; text-align: left;">Medication</th>
          <th style="padding: 10px; text-align: left;">Dosage</th>
          <th style="padding: 10px; text-align: center;">Taken</th>
          <th style="padding: 10px; text-align: center;">Skipped</th>
          <th style="padding: 10px; text-align: center;">Snoozed</th>
          <th style="padding: 10px; text-align: center;">Total</th>
          <th style="padding: 10px; text-align: left;">Adherence</th>
        </tr>
      </thead>
      <tbody>
        ${medicationRows}
      </tbody>
    </table>
  </div>

  <!-- Footer -->
  <div style="border-top: 1px solid #e0e0e0; padding: 16px 32px; text-align: center; font-size: 12px; color: #999; margin-top: 24px;">
    <p style="margin: 0;">Generated by MediBuddy on ${generatedDate}</p>
    <p style="margin: 4px 0 0;">This report is for informational purposes and should be reviewed with a healthcare provider.</p>
  </div>
</body>
</html>`;
}

/** Generate PDF file and return its URI (for sharing) */
export async function generatePDFReport(
  startDate: string,
  endDate: string,
  profileId?: string
): Promise<string> {
  const [medications, overallAdherence, profile] = await Promise.all([
    getAdherenceReport(startDate, endDate, profileId),
    getOverallAdherence(startDate, endDate, profileId),
    getUserProfile(),
  ]);

  const patientName = profile?.name ?? 'Unknown';
  const patientAge = profile?.age ?? 0;

  const html = generateReportHTML(
    patientName,
    patientAge,
    startDate,
    endDate,
    medications,
    overallAdherence
  );

  const { uri } = await Print.printToFileAsync({ html });
  return uri;
}
